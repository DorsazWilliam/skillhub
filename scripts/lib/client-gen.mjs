// Generates the typed SPA client from the operation registry. Shared by gen-client.mjs and check-parity.mjs.
import { register } from 'tsx/esm/api';

register();

const ident = (s) => (/^[A-Za-z_$][\w$]*$/.test(s) ? s : JSON.stringify(s));
const pascal = (s) => s.replace(/(^|_)(\w)/g, (_, __, c) => c.toUpperCase());

/** Minimal JSON Schema -> TypeScript type for the shapes zod emits. */
export function tsType(s, indent = '') {
  if (!s || typeof s !== 'object' || Object.keys(s).length === 0) return 'unknown';
  if (s.anyOf || s.oneOf) return [...new Set((s.anyOf ?? s.oneOf).map((x) => tsType(x, indent)))].join(' | ');
  if (s.const !== undefined) return JSON.stringify(s.const);
  if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join(' | ');
  const types = Array.isArray(s.type) ? s.type : [s.type];
  const parts = types.map((t) => {
    switch (t) {
      case 'string':
        return 'string';
      case 'number':
      case 'integer':
        return 'number';
      case 'boolean':
        return 'boolean';
      case 'null':
        return 'null';
      case 'array':
        return `Array<${tsType(s.items, indent)}>`;
      case 'object': {
        const props = s.properties ?? {};
        const req = new Set(s.required ?? []);
        const keys = Object.keys(props);
        if (keys.length === 0) return s.additionalProperties && typeof s.additionalProperties === 'object' ? `Record<string, ${tsType(s.additionalProperties, indent)}>` : 'Record<string, unknown>';
        const inner = indent + '  ';
        return `{\n${keys.map((k) => `${inner}${ident(k)}${req.has(k) ? '' : '?'}: ${tsType(props[k], inner)};`).join('\n')}\n${indent}}`;
      }
      default:
        return 'unknown';
    }
  });
  return parts.join(' | ');
}

export async function generateClient() {
  const { OPS } = await import('../../src/registry/index.ts');
  const { opSchemas, pathParams } = await import('../../src/http/schema.ts');
  const out = [
    '// GENERATED by scripts/gen-client.mjs from the operation registry. Do not edit.',
    '// Every UI mutation goes through these functions, which call the same REST operations as tokens and MCP.',
    '/* eslint-disable */',
    '',
    'export class ApiError extends Error {',
    '  constructor(public status: number, public code: string, message: string, public details?: Record<string, unknown>) {',
    '    super(message);',
    '  }',
    '}',
    '',
    'async function call<T>(method: string, path: string, input: Record<string, unknown>, params: string[], multipart = false): Promise<T> {',
    '  let url = path;',
    '  const rest: Record<string, unknown> = { ...input };',
    '  for (const p of params) {',
    '    url = url.replace(`{${p}}`, encodeURIComponent(String(rest[p])));',
    '    delete rest[p];',
    '  }',
    "  const init: RequestInit = { method, credentials: 'same-origin', headers: { 'x-skillhub-csrf': '1' } };",
    "  if (method === 'GET' || method === 'DELETE') {",
    '    const q = new URLSearchParams();',
    '    for (const [k, v] of Object.entries(rest)) if (v !== undefined && v !== null) q.set(k, String(v));',
    "    const qs = q.toString();",
    "    if (qs) url += '?' + qs;",
    '  } else if (multipart && rest.file instanceof Blob) {',
    '    const form = new FormData();',
    '    for (const [k, v] of Object.entries(rest)) if (v !== undefined) form.set(k, v as Blob | string);',
    '    init.body = form;',
    '  } else {',
    "    (init.headers as Record<string, string>)['content-type'] = 'application/json';",
    '    init.body = JSON.stringify(rest);',
    '  }',
    "  const res = await fetch('/api/v1' + url, init);",
    '  const body = await res.json().catch(() => null);',
    '  if (!res.ok) {',
    "    const e = (body as { error?: { code: string; message: string; details?: Record<string, unknown> } } | null)?.error;",
    "    throw new ApiError(res.status, e?.code ?? 'internal', e?.message ?? res.statusText, e?.details);",
    '  }',
    '  return body as T;',
    '}',
    '',
  ];
  const entries = [];
  for (const op of OPS) {
    if (!op.rest) continue;
    const { input, output } = opSchemas(op);
    const P = pascal(op.name);
    let inType = tsType(input);
    if (op.rest.multipart) inType = `(${inType}) | { doc: string; file: Blob; alt?: string }`;
    out.push(`/** ${op.summary} (scope: ${op.scope}) */`);
    out.push(`export type ${P}Input = ${inType};`);
    out.push(`export type ${P}Output = ${tsType(output)};`);
    out.push('');
    entries.push(
      `  ${op.name}: (input: ${P}Input${Object.keys(input.properties ?? {}).length === 0 ? ' = {}' : ''}): Promise<${P}Output> => call<${P}Output>(${JSON.stringify(op.rest.method)}, ${JSON.stringify(op.rest.path)}, input as Record<string, unknown>, ${JSON.stringify(pathParams(op.rest.path))}${op.rest.multipart ? ', true' : ''}),`,
    );
  }
  out.push('export const api = {');
  out.push(...entries);
  out.push('} as const;');
  out.push('');
  out.push('/** UI-only operations (SPEC 10.3). Session cookie only; tokens are refused. */');
  out.push('export const uiOnly = {');
  out.push("  login: (returnTo = '/'): void => { window.location.href = '/auth/login?return_to=' + encodeURIComponent(returnTo); },");
  out.push("  logout: (): Promise<{ ok: boolean }> => call('POST', '/ui/logout', {}, []),");
  out.push("  mint_api_token: (input: { name: string; scopes: Array<'read' | 'write' | 'publish' | 'manage' | 'admin'>; expires_in_days?: number | null }): Promise<{ id: string; token: string; name: string; scopes: string[]; expires_at: number | null }> => call('POST', '/ui/tokens', input, []),");
  out.push("  revoke_api_token: (input: { id: string }): Promise<{ revoked: boolean }> => call('DELETE', '/ui/tokens/{id}', input, ['id']),");
  out.push("  revoke_mcp_connection: (input: { id: string }): Promise<{ revoked: boolean }> => call('DELETE', '/ui/connections/{id}', input, ['id']),");
  out.push('} as const;');
  out.push('');
  return out.join('\n');
}
