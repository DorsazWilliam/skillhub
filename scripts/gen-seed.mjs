// Generates migrations/0002_seed_hub.sql from src/seed/*.md.
// Usage: node scripts/gen-seed.mjs
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { register } from 'tsx/esm/api';

register();
const { skillMeta, splitFrontmatter } = await import('../src/lib/frontmatter.ts');
const { stripMarkdown } = await import('../src/lib/markdown.ts');

const q = (s) => (s === null || s === undefined ? 'NULL' : `'${String(s).replace(/'/g, "''")}'`);

// Fixed ULIDs keep the seed deterministic across instances.
const HUB = '0'.repeat(24) + 'HB';
const docs = [
  { id: '0'.repeat(23) + 'HB1', file: 'hub-authoring' },
  { id: '0'.repeat(23) + 'HB2', file: 'hub-promote' },
  { id: '0'.repeat(23) + 'HB3', file: 'hub-access' },
];

const lines = [
  '-- Generated by scripts/gen-seed.mjs. Built-in skills, readable by everyone, editable by owners only.',
  `INSERT INTO nodes (id, parent_id, kind, name, path, inherit, created_by, created_at, updated_at) VALUES (${q(HUB)}, NULL, 'folder', '_hub', '/${HUB}/', 0, 'system', 0, 0);`,
  `INSERT INTO grants (id, node_id, principal_type, principal_id, role, created_by, created_at) VALUES ('${'0'.repeat(22)}GRNT', ${q(HUB)}, 'team', 'everyone', 1, 'system', 0);`,
];
for (const d of docs) {
  const content = readFileSync(new URL(`../src/seed/${d.file}.md`, import.meta.url), 'utf8').replace(/\r\n/g, '\n');
  const meta = skillMeta(content);
  if (!meta) throw new Error(`${d.file} has invalid frontmatter`);
  const sha = createHash('sha256').update(content).digest('hex');
  const body = stripMarkdown(splitFrontmatter(content).body);
  lines.push(
    `INSERT INTO nodes (id, parent_id, kind, name, path, inherit, head_version, published_version, is_skill, created_by, created_at, updated_at) VALUES (${q(d.id)}, ${q(HUB)}, 'doc', ${q(d.file)}, '/${HUB}/${d.id}/', 1, 1, 1, 1, 'system', 0, 0);`,
    `INSERT INTO doc_versions (doc_id, n, content, sha256, message, author_id, created_at) VALUES (${q(d.id)}, 1, ${q(content)}, ${q(sha)}, 'Built-in skill', 'system', 0);`,
    `INSERT INTO skill_fts (doc_id, name, description, body) VALUES (${q(d.id)}, ${q(meta.name)}, ${q(meta.description)}, ${q(body)});`,
  );
}
writeFileSync(new URL('../migrations/0002_seed_hub.sql', import.meta.url), lines.join('\n') + '\n');
console.log('wrote migrations/0002_seed_hub.sql');
