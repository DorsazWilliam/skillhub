// Generates the built-in skill update migration from src/seed/*.md.
// Usage: node scripts/gen-seed.mjs
//
// migrations/0002_seed_hub.sql (the original seed) is frozen: applied migrations are never edited.
// This script writes TARGET, which adds the current text of each built-in skill as a new version
// (skipped when an identical version exists) and publishes it only where the published version is
// still one written by the system, so an owner's own edits are never replaced.
// When the seed text changes again after TARGET has shipped, point TARGET at a new migration number.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { register } from 'tsx/esm/api';

register();
const { skillMeta, splitFrontmatter } = await import('../src/lib/frontmatter.ts');
const { stripMarkdown } = await import('../src/lib/markdown.ts');

const TARGET = '0004_seed_hub_v2.sql';

const q = (s) => (s === null || s === undefined ? 'NULL' : `'${String(s).replace(/'/g, "''")}'`);

// Fixed ids from 0002 (documents) and 0003 (their skill folders).
const docs = [
  { id: '0'.repeat(23) + 'HB1', file: 'hub-authoring' },
  { id: '0'.repeat(23) + 'HB2', file: 'hub-promote' },
  { id: '0'.repeat(23) + 'HB3', file: 'hub-access' },
];

const lines = [`-- Generated by scripts/gen-seed.mjs. Current text of the built-in skills; see the script header.`];
for (const d of docs) {
  const content = readFileSync(new URL(`../src/seed/${d.file}.md`, import.meta.url), 'utf8').replace(/\r\n/g, '\n');
  const meta = skillMeta(content);
  if (!meta) throw new Error(`${d.file} has invalid frontmatter`);
  const sha = createHash('sha256').update(content).digest('hex');
  const body = stripMarkdown(splitFrontmatter(content).body);
  const id = q(d.id);
  const target = `(SELECT n FROM doc_versions WHERE doc_id = ${id} AND sha256 = ${q(sha)} ORDER BY n DESC LIMIT 1)`;
  const isPublished = `(SELECT published_version FROM nodes WHERE id = ${id}) = ${target}`;
  lines.push(
    '',
    `-- ${d.file}`,
    `INSERT INTO doc_versions (doc_id, n, content, sha256, message, author_id, created_at)
  SELECT id, head_version + 1, ${q(content)}, ${q(sha)}, 'Built-in skill update', 'system', 0 FROM nodes
  WHERE id = ${id} AND deleted_at IS NULL AND NOT EXISTS (SELECT 1 FROM doc_versions WHERE doc_id = ${id} AND sha256 = ${q(sha)});`,
    `UPDATE nodes SET head_version = (SELECT MAX(n) FROM doc_versions WHERE doc_id = ${id}) WHERE id = ${id} AND deleted_at IS NULL;`,
    `UPDATE nodes SET published_version = ${target}, is_skill = 1
  WHERE id = ${id} AND deleted_at IS NULL AND (SELECT author_id FROM doc_versions WHERE doc_id = ${id} AND n = nodes.published_version) = 'system';`,
    `DELETE FROM skill_fts WHERE doc_id = ${id} AND ${isPublished};`,
    `INSERT INTO skill_fts (doc_id, name, description, body) SELECT ${id}, ${q(meta.name)}, ${q(meta.description)}, ${q(body)} WHERE ${isPublished};`,
  );
}
writeFileSync(new URL(`../migrations/${TARGET}`, import.meta.url), lines.join('\n') + '\n');
console.log(`wrote migrations/${TARGET}`);
